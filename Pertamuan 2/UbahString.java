package Praktikum;

public class UbahString {
    public static void main(String[] args) {
        String a = "Saya Belajar Java"; 
        String b = "Saya Belajar Java"; 
        
        System.out.println(a.toLowerCase()); // menjadi "saya belajar java"
        System.out.println(b.toUpperCase()); // menjadi "SAYA BELAJAR JAVA"
    }
}
