package Praktikum;

public class Aritmatika {
    public static void main(String[] args) {
        double ang1 = 22;
        double ang2 = 33;
        
        System.out.println("Hasil dari 12+15: " + (ang1 + ang2));
        System.out.println("Hasil dari 12-15: " + (ang1 - ang2));
        System.out.println("Hasil dari 12*15: " + (ang1 * ang2));
        System.out.println("Hasil dari 12/15: " + (ang1 / ang2));
    }
}
